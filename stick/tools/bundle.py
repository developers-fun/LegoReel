"""Pack the whole stickreel project into ONE text file, or unpack it again.

  python3 tools/bundle.py                      writes stickreel_bundle.md (README, live docs, every source file, tests, scene, skill)
  python3 tools/bundle.py --extract FILE OUT   rebuilds the folder tree under OUT (then: cd OUT/stick && python3 -m stickreel docs)

Format: <!-- FILE path --> then a code fence of 6 backticks around the file. Plain text, so an agent can read it directly.
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
STICK = os.path.dirname(HERE)
ROOT = os.path.dirname(STICK)
FENCE = "`" * 6

INCLUDE = [
    "CLAUDE.md", "docs/BRAIN_SYSTEM_PROMPT.md", ".claude/skills/stickmation/SKILL.md",
    "stick/README.md", "stick/NOTES.md", "stick/data/fit_all11.json", "stick/scenes/dig_skit.py",
    "stick/tools/bundle.py",
]
SKIP_DIRS = {"__pycache__", "out"}


def collect():
    files = [f for f in INCLUDE if os.path.exists(os.path.join(ROOT, f))]
    for sub in ("stick/stickreel", "stick/tests"):
        for n in sorted(os.listdir(os.path.join(ROOT, sub))):
            if n.endswith(".py"):
                files.append(f"{sub}/{n}")
    return files


def make(out):
    docs = subprocess.run([sys.executable, "-m", "stickreel", "docs"], cwd=STICK, capture_output=True, text=True).stdout
    parts = ["# stickreel: the whole thing in one file\n",
             "Generated by `stick/tools/bundle.py`. Restore with `python3 tools/bundle.py --extract THIS_FILE OUTDIR`. "
             "Needs numpy, Pillow, ffmpeg and the font `fonts/Poppins-Bold.ttf` from the LegoReel repo (not bundled; any bold TTF works if you edit `engine.py`).\n",
             "## Live reference (`python3 -m stickreel docs`)\n", FENCE + "text\n" + docs.rstrip() + "\n" + FENCE + "\n"]
    for f in collect():
        text = open(os.path.join(ROOT, f), encoding="utf-8").read()
        assert FENCE not in text, f"{f} contains the fence"
        lang = {"py": "python", "md": "markdown", "json": "json"}.get(f.rsplit(".", 1)[-1], "")
        parts.append(f"\n<!-- FILE {f} -->\n{FENCE}{lang}\n{text.rstrip(chr(10))}\n{FENCE}\n")
    open(out, "w", encoding="utf-8").write("\n".join(parts))
    print(f"wrote {out}: {os.path.getsize(out) / 1024:.0f} KB, {len(collect())} files")


def extract(src, dst):
    text = open(src, encoding="utf-8").read()
    n = 0
    for m in re.finditer(r"<!-- FILE (.+?) -->\n(`{6})\w*\n(.*?)\n\2\n", text, re.S):
        path = os.path.join(dst, m.group(1))
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, "w", encoding="utf-8").write(m.group(3) + "\n")
        n += 1
    print(f"extracted {n} files under {dst}")


if __name__ == "__main__":
    if len(sys.argv) >= 4 and sys.argv[1] == "--extract":
        extract(sys.argv[2], sys.argv[3])
    else:
        make(os.path.join(STICK, "stickreel_bundle.md"))
